function toDataUri(buffer, type) {
  return `data:${type};base64,${buffer.toString('base64')}`
}

let output = `/**
 * Generated by scripts/generate-art.mjs — do not edit by hand.
 *
 * All artwork is embedded as base64 data URIs so the packed skin is fully
 * self-contained. Artwork source:
 * - 《哀鸿：城破十日记》同人角色「林翩翩」立绘
 * - B 站作者：露痴了么
 * - Project and third-party terms: see LICENSE, LICENSE-ASSETS.md, and NOTICE.
 */

`

output += 'export const LINPIANPIAN_ART = {\n'
for (const [name, asset] of Object.entries(THEME_ART)) {
  const source = await readFile(asset.source)
  output += `  ${JSON.stringify(name)}: [\n`
  const dataUri = toDataUri(source, asset.type)
  for (let index = 0; index < dataUri.length; index += 20000) {
    output += `    ${JSON.stringify(dataUri.slice(index, index + 20000))},\n`
  }
  output += '  ].join(\'\'),\n'
}
output += '} as const\n'

const target = resolve(projectRoot, 'src/client/art.generated.ts')
await mkdir(dirname(target), { recursive: true })
await writeFile(target, output)
console.log(`[generate-art] wrote ${target} (${output.length} chars)`)
