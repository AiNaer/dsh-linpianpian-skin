/**
 * Regenerate src/client/art.generated.ts from the baked skin artwork in
 * assets/. Every final is a small webp (the favicon and paper texture stay
 * png) embedded as a base64 data URI so the packed skin never reads a file
 * or URL at runtime.
 *
 * Baked assets come from scripts/bake-art.py — run it first:
 *   python scripts/bake-art.py
 *   node scripts/generate-art.mjs
 */
